    function getStoredLanguage() {
        var language = root.localStorage.getItem('metro-map-studio-language');
        return language === 'en' || language === 'tr' || language === 'zh-CN' ? language : 'tr';
    }

    var language = getStoredLanguage();

    function t(key, params) {
        var value = messages[language][key] || messages.tr[key] || key;
        return String(value).replace(/\{(\w+)\}/g, function (match, name) {
            return params && Object.prototype.hasOwnProperty.call(params, name) ? params[name] : match;
        });
    }

    function apply() {
        document.documentElement.lang = language;
        document.title = t('pageTitle');
        var description = document.querySelector('meta[name="description"]');
        if (description) description.setAttribute('content', t('description'));
        Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), function (el) {
            el.textContent = t(el.getAttribute('data-i18n'));
        });
        Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-html]'), function (el) {
            el.innerHTML = t(el.getAttribute('data-i18n-html'));
        });
        Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-placeholder]'), function (el) {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
        });
        Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-alt]'), function (el) {
            el.setAttribute('alt', t(el.getAttribute('data-i18n-alt')));
        });
        Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-value]'), function (el) {
            el.value = t(el.getAttribute('data-i18n-value'));
        });
        var languageSelect = document.getElementById('languageSelect');
        if (languageSelect) {
            languageSelect.value = language;
            languageSelect.setAttribute('aria-label', t('languageSelectAria'));
        }
    }

    function setLanguage(nextLanguage) {
        if (nextLanguage !== 'tr' && nextLanguage !== 'en' && nextLanguage !== 'zh-CN') {
            throw new Error('Unsupported language: ' + nextLanguage);
        }
        language = nextLanguage;
        root.localStorage.setItem('metro-map-studio-language', language);
        apply();
    }

    MMS.i18n = {
        t: t,
        getLanguage: function () {
            return language;
        },
        setLanguage: setLanguage,
        apply: apply
    };

    apply();
